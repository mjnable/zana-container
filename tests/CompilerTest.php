<?php

declare(strict_types=1);

namespace Zana\Container\Tests;

use PHPUnit\Framework\TestCase;
use Zana\Container\ContainerCompiler;
use Zana\Container\Exception\ContainerBuildException;
use Zana\Container\Exception\ContainerException;
use Zana\Container\Exception\StaleCompilationException;
use Zana\Container\ServiceCollection;
use Zana\Container\Tests\Fixtures\Clock;
use Zana\Container\Tests\Fixtures\FileLogger;
use Zana\Container\Tests\Fixtures\LoggerInterface;
use Zana\Container\Tests\Fixtures\Mailer;
use Zana\Container\Tests\Fixtures\NeedsScalar;
use Zana\Container\Tests\Fixtures\NullLogger;

final class CompilerTest extends TestCase
{
    private static int $counter = 0;

    public function testGeneratedSourceIsAFinalClassWithFingerprintAndData(): void
    {
        $source = (new ContainerCompiler())->compile($this->collection(), 'App\\Cache\\Container');

        $this->assertStringContainsString("namespace App\\Cache;", $source);
        $this->assertStringContainsString('final class Container extends \\Zana\\Container\\Compiled\\CompiledContainer', $source);
        $this->assertMatchesRegularExpression("/public const FINGERPRINT = '[0-9a-f]{32}';/", $source);
    }

    public function testCompiledContainerResolvesLikeTheRuntimeOne(): void
    {
        $class = $this->compile($this->collection());

        $container = $this->collection()->build(compiled: $class);
        $mailer = $container->get(Mailer::class);

        $this->assertInstanceOf(Mailer::class, $mailer);
        $this->assertSame($container->get(LoggerInterface::class), $mailer->logger);
        $this->assertEquals($this->collection()->build()->graph(), $container->graph());
    }

    public function testCompiledBuildSkipsScanning(): void
    {
        $namespace = 'ZanaScanTemp' . ++self::$counter;
        $directory = sys_get_temp_dir() . DIRECTORY_SEPARATOR . $namespace;
        mkdir($directory);
        $file = $directory . DIRECTORY_SEPARATOR . 'TempService.php';
        file_put_contents($file, "<?php\nnamespace {$namespace};\n#[\\Zana\\Container\\Attribute\\Singleton]\nfinal class TempService {}\n");
        require $file;

        try {
            $class = $this->compile((new ServiceCollection())->scan($directory, $namespace));
        } finally {
            unlink($file);
            rmdir($directory);
        }

        // The directory is gone: a runtime build would fail with B13.
        $container = (new ServiceCollection())->scan($directory, $namespace)->build(compiled: $class);

        $this->assertTrue($container->has("{$namespace}\\TempService"));
    }

    public function testStaleCompiledClassesAreRejected(): void
    {
        $class = $this->compile($this->collection());

        $this->expectException(StaleCompilationException::class);
        $this->expectExceptionMessage('is stale');
        $this->collection()->singleton(Clock::class)->build(compiled: $class);
    }

    public function testFingerprintIgnoresClosureIdentityButNotRegistrationChanges(): void
    {
        $make = static fn (string $logger): ServiceCollection => (new ServiceCollection())
            ->singleton(LoggerInterface::class, $logger)
            ->transient('clock', static fn (): Clock => new Clock());

        $class = $this->compile($make(FileLogger::class));

        $this->assertInstanceOf(Clock::class, $make(FileLogger::class)->build(compiled: $class)->get('clock'));

        $this->expectException(StaleCompilationException::class);
        $make(NullLogger::class)->build(compiled: $class);
    }

    public function testOnlyGeneratedClassesAreAccepted(): void
    {
        $this->expectException(StaleCompilationException::class);
        $this->expectExceptionMessage('is not a container generated by ContainerCompiler');

        $this->collection()->build(compiled: Clock::class);
    }

    public function testInvalidRegistrationsCannotBeCompiled(): void
    {
        $this->expectException(ContainerBuildException::class);

        (new ContainerCompiler())->compile((new ServiceCollection())->transient(NeedsScalar::class), 'App\\Broken');
    }

    public function testInvalidClassNamesAreRejected(): void
    {
        $this->expectException(ContainerException::class);

        (new ContainerCompiler())->compile($this->collection(), 'App\\Not A Class');
    }

    private function collection(): ServiceCollection
    {
        return (new ServiceCollection())
            ->singleton(LoggerInterface::class, FileLogger::class)
            ->transient(Mailer::class);
    }

    /**
     * @return class-string
     */
    private function compile(ServiceCollection $services): string
    {
        $class = 'ZanaCompilerTest\\Compiled' . ++self::$counter;
        $file = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'zana-compiler-test-' . getmypid() . '-' . self::$counter . '.php';
        file_put_contents($file, (new ContainerCompiler())->compile($services, $class));
        require $file;
        unlink($file);

        /** @var class-string $class */
        return $class;
    }
}
