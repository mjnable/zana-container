<?php

declare(strict_types=1);

namespace Zana\Container;

use Zana\Container\Compiled\CompiledContainer;
use Zana\Container\Contracts\ServiceCollectionInterface;
use Zana\Container\Exception\ContainerException;

/**
 * Generates a compiled container class for production (specification §11).
 *
 *     $source = (new ContainerCompiler())->compile($services, 'App\\CompiledContainer');
 *     file_put_contents($path, $source);              // storing it is the caller's job
 *
 *     $container = $services->build(compiled: \App\CompiledContainer::class);
 *
 * The class holds the validated construction plans, the scan results and the
 * graph, so a compiled build skips validation, scanning and attribute reading.
 * Closures, instances, providers, interceptors and observers still come from
 * the live collection. Recompile whenever registrations or the constructors
 * of registered classes change; a fingerprint check rejects stale classes.
 */
final class ContainerCompiler
{
    /**
     * @param string $className Fully qualified name of the class to generate
     * @return string PHP source code
     * @throws \Zana\Container\Exception\ContainerBuildException If the registrations are invalid
     */
    public function compile(ServiceCollectionInterface $services, string $className): string
    {
        if (!$services instanceof ServiceCollection) {
            throw new ContainerException('ContainerCompiler can only compile a ' . ServiceCollection::class . '.');
        }

        $className = ltrim($className, '\\');
        if (preg_match('/^([A-Za-z_][A-Za-z0-9_]*\\\\)*[A-Za-z_][A-Za-z0-9_]*$/', $className) !== 1) {
            throw new ContainerException("Invalid class name for a compiled container: {$className}.");
        }

        $compilation = $services->compilation();

        $position = strrpos($className, '\\');
        $namespace = $position === false ? '' : substr($className, 0, $position);
        $shortName = $position === false ? $className : substr($className, $position + 1);

        return sprintf(
            <<<'PHP'
            <?php

            declare(strict_types=1);
            %s
            /**
             * Compiled container generated by Zana\Container\ContainerCompiler. Do not edit:
             * regenerate it when the service registrations change.
             */
            final class %s extends \%s
            {
                public const FINGERPRINT = %s;

                public static function data(): array
                {
                    return %s;
                }
            }

            PHP,
            $namespace === '' ? '' : "\nnamespace {$namespace};\n",
            $shortName,
            CompiledContainer::class,
            var_export($compilation['fingerprint'], true),
            var_export($compilation['data'], true),
        );
    }
}
