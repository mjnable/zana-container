<?php

declare(strict_types=1);

namespace Zana\Container\Exception;

/**
 * Thrown by ServiceCollection::build(compiled: ...) when the compiled class was
 * generated from different registrations.
 */
class StaleCompilationException extends ContainerException
{
    public static function for(string $class, string $expected, string $actual): self
    {
        return new self(sprintf(
            'The compiled container %s is stale: it was generated for fingerprint %s, but the registrations now have fingerprint %s. Recompile it with ContainerCompiler.',
            $class,
            $expected,
            $actual
        ));
    }

    public static function notCompiled(string $class): self
    {
        return new self("{$class} is not a container generated by ContainerCompiler.");
    }
}
